DROP SCHEMA IF EXISTS star CASCADE;
CREATE SCHEMA star;

CREATE TABLE star.dim_date (
    date_key          INT PRIMARY KEY,
    calendar_date     DATE UNIQUE,
    year              SMALLINT,
    quarter           SMALLINT,
    month             SMALLINT,
    month_name        VARCHAR(10),
    year_month        CHAR(7),
    month_start_date  DATE,
    day_of_month      SMALLINT,
    day_of_week       SMALLINT,
    day_name          VARCHAR(10),
    week_of_year      SMALLINT,
    is_weekend        BOOLEAN
);

CREATE TABLE star.dim_patient (
    patient_key    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id     INT UNIQUE,
    mrn            VARCHAR(20),
    first_name     VARCHAR(100),
    last_name      VARCHAR(100),
    full_name      VARCHAR(201),
    gender         VARCHAR(10),
    date_of_birth  DATE,
    age_group      VARCHAR(10),
    created_at     TIMESTAMP NOT NULL DEFAULT now(),
    updated_at     TIMESTAMP NOT NULL DEFAULT now()
);

CREATE TABLE star.dim_specialty (
    specialty_key   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    specialty_id    INT UNIQUE,
    specialty_name  VARCHAR(100),
    specialty_code  VARCHAR(10)
);

CREATE TABLE star.dim_department (
    department_key   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id    INT UNIQUE,
    department_name  VARCHAR(100),
    floor            INT,
    capacity         INT
);

CREATE TABLE star.dim_provider (
    provider_key     INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id      INT,
    first_name       VARCHAR(100),
    last_name        VARCHAR(100),
    full_name        VARCHAR(201),
    credential       VARCHAR(20),
    specialty_id     INT,
    specialty_name   VARCHAR(100),
    department_id    INT,
    department_name  VARCHAR(100),
    effective_date   DATE    NOT NULL,
    end_date         DATE    NOT NULL DEFAULT DATE '9999-12-31',
    is_current       BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (provider_id, effective_date)
);

CREATE INDEX idx_dim_provider_current ON star.dim_provider (provider_id) WHERE is_current;

CREATE TABLE star.dim_encounter_type (
    encounter_type_key   INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    encounter_type_name  VARCHAR(50) UNIQUE,
    is_inpatient         BOOLEAN,
    is_emergency         BOOLEAN
);

CREATE TABLE star.dim_diagnosis (
    diagnosis_key      INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diagnosis_id       INT UNIQUE,
    icd10_code         VARCHAR(10),
    icd10_description  VARCHAR(200)
);

CREATE TABLE star.dim_procedure (
    procedure_key    INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procedure_id     INT UNIQUE,
    cpt_code         VARCHAR(10),
    cpt_description  VARCHAR(200)
);

CREATE TABLE star.fact_encounters (
    encounter_key             INT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    encounter_id              INT NOT NULL UNIQUE,
    encounter_date_key        INT NOT NULL REFERENCES star.dim_date (date_key),
    discharge_date_key        INT NOT NULL REFERENCES star.dim_date (date_key),
    patient_key               INT NOT NULL REFERENCES star.dim_patient (patient_key),
    provider_key              INT NOT NULL REFERENCES star.dim_provider (provider_key),
    specialty_key             INT NOT NULL REFERENCES star.dim_specialty (specialty_key),
    department_key            INT NOT NULL REFERENCES star.dim_department (department_key),
    encounter_type_key        INT NOT NULL REFERENCES star.dim_encounter_type (encounter_type_key),
    primary_diagnosis_key     INT NOT NULL REFERENCES star.dim_diagnosis (diagnosis_key),
    encounter_count           SMALLINT      NOT NULL DEFAULT 1,
    length_of_stay_hours      NUMERIC(10,2),
    length_of_stay_days       INT,
    patient_age_at_encounter  SMALLINT,
    diagnosis_count           SMALLINT      NOT NULL DEFAULT 0,
    procedure_count           SMALLINT      NOT NULL DEFAULT 0,
    claim_count               SMALLINT      NOT NULL DEFAULT 0,
    total_claim_amount        NUMERIC(12,2) NOT NULL DEFAULT 0,
    total_allowed_amount      NUMERIC(12,2) NOT NULL DEFAULT 0,
    is_readmission_30d        SMALLINT      NOT NULL DEFAULT 0 CHECK (is_readmission_30d IN (0, 1)),
    loaded_at                 TIMESTAMP     NOT NULL DEFAULT now()
);

CREATE INDEX idx_fact_enc_date       ON star.fact_encounters (encounter_date_key);
CREATE INDEX idx_fact_enc_patient    ON star.fact_encounters (patient_key);
CREATE INDEX idx_fact_enc_provider   ON star.fact_encounters (provider_key);
CREATE INDEX idx_fact_enc_specialty  ON star.fact_encounters (specialty_key);
CREATE INDEX idx_fact_enc_department ON star.fact_encounters (department_key);
CREATE INDEX idx_fact_enc_type       ON star.fact_encounters (encounter_type_key);
CREATE INDEX idx_fact_enc_type_spec  ON star.fact_encounters (encounter_type_key, specialty_key);

CREATE TABLE star.bridge_encounter_diagnoses (
    encounter_key       INT NOT NULL REFERENCES star.fact_encounters (encounter_key),
    diagnosis_key       INT NOT NULL REFERENCES star.dim_diagnosis (diagnosis_key),
    diagnosis_sequence  SMALLINT,
    is_primary          BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (encounter_key, diagnosis_key)
);

CREATE INDEX idx_bridge_dx_diagnosis ON star.bridge_encounter_diagnoses (diagnosis_key);

CREATE TABLE star.bridge_encounter_procedures (
    encounter_key       INT NOT NULL REFERENCES star.fact_encounters (encounter_key),
    procedure_key       INT NOT NULL REFERENCES star.dim_procedure (procedure_key),
    procedure_date_key  INT REFERENCES star.dim_date (date_key),
    PRIMARY KEY (encounter_key, procedure_key)
);

CREATE INDEX idx_bridge_px_procedure ON star.bridge_encounter_procedures (procedure_key);

COMMENT ON SCHEMA star IS 'Dimensional model (star schema) for healthcare encounter analytics, loaded from schema oltp.';
COMMENT ON TABLE star.dim_date IS 'Calendar dimension, one row per day (2020-2030). date_key = YYYYMMDD; key 0 = unknown date. Replaces per-row date functions with stored year/quarter/month attributes.';
COMMENT ON TABLE star.dim_patient IS 'Patient dimension. SCD Type 1 (corrections overwrite). Gender standardized, age_group derived. Key -1 = unknown patient.';
COMMENT ON TABLE star.dim_specialty IS 'Medical specialty dimension. Stored directly on the fact so specialty reports need one join. Key -1 = unknown.';
COMMENT ON TABLE star.dim_department IS 'Hospital department dimension (name, floor, capacity). Key -1 = unknown.';
COMMENT ON TABLE star.dim_provider IS 'Provider dimension, SCD Type 2: one row per version, tracked with effective_date, end_date, is_current. Specialty and department names denormalized. Key -1 = unknown.';
COMMENT ON TABLE star.dim_encounter_type IS 'Encounter type dimension (Outpatient, Inpatient, ER) with helper flags. Key -1 = unknown.';
COMMENT ON TABLE star.dim_diagnosis IS 'ICD-10 diagnosis dimension, used via bridge_encounter_diagnoses and fact.primary_diagnosis_key. Key -1 = unknown/none.';
COMMENT ON TABLE star.dim_procedure IS 'CPT procedure dimension, used via bridge_encounter_procedures. Key -1 = unknown.';
COMMENT ON TABLE star.fact_encounters IS 'Transaction fact table. Grain: one row per encounter. Holds dimension keys plus pre-aggregated measures (billing totals, diagnosis/procedure counts, length of stay, 30-day readmission flag).';
COMMENT ON TABLE star.bridge_encounter_diagnoses IS 'Bridge for the many-to-many encounter-diagnosis relationship. One row per diagnosis per encounter. Do not SUM fact measures after joining this table.';
COMMENT ON TABLE star.bridge_encounter_procedures IS 'Bridge for the many-to-many encounter-procedure relationship. One row per procedure per encounter. Do not SUM fact measures after joining this table.';